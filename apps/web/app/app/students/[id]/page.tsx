import Link from "next/link";
import { requireCollegeAdmin } from "@/lib/auth/require-college-admin";
import { createClient } from "@/lib/supabase/server";
import { READINESS_LABEL, readinessBand } from "@/lib/readiness";
import { isStubReport } from "@/lib/ai-stubs/interview-engine";

// Dynamic route param: Next.js 16 passes `params` as a Promise (see
// node_modules/next/dist/docs/01-app/.../dynamic-routes.md) — must be
// awaited. Deliberately typed inline rather than with the generated
// `PageProps<'/app/students/[id]'>` helper, same reasoning as the root
// layout (docs/DECISIONS.md, Phase 0): that type only exists after
// `.next/types/` has been generated by a build, so a `tsc --noEmit` on a
// fresh clone would fail before the first build.
interface StudentDetailPageProps {
  params: Promise<{ id: string }>;
}

// This project has no generated Database type for the Supabase client (see
// lib/supabase/client.ts/server.ts — createClient() takes no generic), so
// an embedded-relation select like "batches(name)" can't be typed from the
// select string alone: postgrest-js's type-level parser needs the schema
// to know a profile has at most one batch, and without it infers a
// to-many array instead. Cast to the real shape once here, the same way
// lib/auth/current-profile.ts casts its own untyped query result.
interface StudentProfileRow {
  id: string;
  full_name: string | null;
  email: string;
  department: string | null;
  graduation_year: number | null;
  batch_id: string | null;
  batches: { name: string } | null;
}

// docs/BUILD_SPEC.md Part 4.7: "Student detail: read-only view of reports
// and resume." Per the live RLS policies, a college_admin's read access to
// a student's data is explicitly limited to interview_reports/weak_areas
// (via college_id) and resumes (via the profile_college_id() helper) — NOT
// job_descriptions or resume_scans, which have no college_admin policy at
// all (see supabase/migrations/20261015120007_row_level_security.sql).
// This page deliberately shows neither, even though both tables exist.
export default async function StudentDetailPage({ params }: StudentDetailPageProps) {
  await requireCollegeAdmin();
  const { id } = await params;
  const supabase = await createClient();

  // RLS (profiles_select) only returns this row at all if the student is
  // in the caller's own college — a college_admin pointing this page at a
  // student from a different college gets no row back, not someone else's
  // data. We also pin role = 'student' so this page can't be used to
  // "view" a fellow admin's profile.
  const { data: studentRow } = await supabase
    .from("profiles")
    .select("id, full_name, email, department, graduation_year, batch_id, batches(name)")
    .eq("id", id)
    .eq("role", "student")
    .maybeSingle();
  const student = studentRow as unknown as StudentProfileRow | null;

  if (!student) {
    return (
      <div className="max-w-2xl space-y-4">
        <Link href="/app/students" className="font-body text-sm text-muted-foreground hover:text-foreground">
          &larr; Back to students
        </Link>
        <p className="rounded-3xl border border-border bg-card p-8 font-body text-sm text-muted-foreground shadow-soft">
          No student found with this link. They may not exist, or may not be part of your college.
        </p>
      </div>
    );
  }

  const [reportsRes, weakAreasRes, resumesRes] = await Promise.all([
    supabase
      .from("interview_reports")
      // A template literal with no interpolation is still a string LITERAL
      // type to TypeScript (unlike `"a" + "b"`, which widens to plain
      // `string` and breaks postgrest-js's select-string type parser with
      // a "Received a generic string" error) — written across lines only
      // for readability.
      .select(
        `id, status, overall_score, strengths, weak_areas_summary, practice_actions, model_id, created_at,
         interviews(interview_type, target_role, company_type, difficulty, started_at, ended_at, duration_seconds, status)`,
      )
      .eq("user_id", id)
      .order("created_at", { ascending: false }),
    supabase
      .from("weak_areas")
      .select("id, skill, severity, is_resolved, notes, created_at")
      .eq("user_id", id)
      .order("created_at", { ascending: false }),
    supabase
      .from("resumes")
      .select("id, title, template, data, version, is_primary, updated_at")
      .eq("user_id", id)
      .order("is_primary", { ascending: false })
      .order("updated_at", { ascending: false }),
  ]);

  // Cast for the same reason as StudentProfileRow above: without a
  // generated Database type, the "interviews(...)" embed types as a
  // to-many array by default, when a report actually has at most one
  // interview (interview_reports.interview_id is unique).
  const reports = (reportsRes.data ?? []) as unknown as ReportRow[];
  const weakAreas = weakAreasRes.data ?? [];
  const resume = (resumesRes.data ?? [])[0] ?? null;

  const latestCompleted = reports.find((r) => r.status === "completed") ?? null;
  const band = readinessBand(latestCompleted?.overall_score != null ? Number(latestCompleted.overall_score) : null);
  const bandIsPreview = latestCompleted ? isStubReport(latestCompleted.model_id) : false;

  return (
    <div className="max-w-4xl space-y-6">
      <Link href="/app/students" className="font-body text-sm text-muted-foreground hover:text-foreground">
        &larr; Back to students
      </Link>

      <div className="rounded-3xl border border-border bg-card p-6 shadow-soft">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <h1 className="text-2xl font-semibold text-foreground">{student.full_name ?? student.email}</h1>
            <p className="mt-1 font-body text-sm text-muted-foreground">{student.email}</p>
          </div>
          <span className="inline-flex items-center gap-1.5 rounded-full bg-muted px-3 py-1 font-body text-xs font-medium text-foreground">
            {READINESS_LABEL[band]}
            {bandIsPreview && <span className="font-semibold uppercase tracking-wide text-amber-600">(preview)</span>}
          </span>
        </div>
        <dl className="mt-4 grid grid-cols-2 gap-3 font-body text-sm sm:grid-cols-3">
          <Field label="Batch" value={student.batches?.name ?? "—"} />
          <Field label="Department" value={student.department ?? "—"} />
          <Field label="Graduation year" value={student.graduation_year ? String(student.graduation_year) : "—"} />
        </dl>
      </div>

      <section className="rounded-3xl border border-border bg-card p-6 shadow-soft">
        <h2 className="font-headline text-lg text-foreground">Interview reports</h2>
        {reports.length === 0 ? (
          <EmptyNote text="No interviews completed yet." />
        ) : (
          <div className="mt-4 space-y-4">
            {reports.map((report) => (
              <ReportCard key={report.id} report={report} />
            ))}
          </div>
        )}
      </section>

      <section className="rounded-3xl border border-border bg-card p-6 shadow-soft">
        <h2 className="font-headline text-lg text-foreground">Weak areas</h2>
        {weakAreas.length === 0 ? (
          <EmptyNote text="No weak areas recorded yet." />
        ) : (
          <ul className="mt-4 space-y-2">
            {weakAreas.map((area) => (
              <li
                key={area.id}
                className="flex items-center justify-between rounded-xl border border-border bg-background px-4 py-2"
              >
                <div>
                  <p className="font-body text-sm text-foreground">{area.skill}</p>
                  {area.notes && <p className="font-body text-xs text-muted-foreground">{area.notes}</p>}
                </div>
                <span className="font-body text-xs font-medium capitalize text-muted-foreground">
                  {area.is_resolved ? "resolved" : area.severity}
                </span>
              </li>
            ))}
          </ul>
        )}
      </section>

      <section className="rounded-3xl border border-border bg-card p-6 shadow-soft">
        <h2 className="font-headline text-lg text-foreground">Resume</h2>
        {!resume ? (
          <EmptyNote text="This student hasn't built a resume yet." />
        ) : (
          <ResumeView resume={resume} />
        )}
      </section>
    </div>
  );
}

function Field({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="text-xs uppercase tracking-label text-muted-foreground">{label}</dt>
      <dd className="mt-0.5 text-foreground">{value}</dd>
    </div>
  );
}

function EmptyNote({ text }: { text: string }) {
  return (
    <p className="mt-4 rounded-2xl border border-dashed border-border bg-background px-4 py-6 text-center font-body text-sm text-muted-foreground">
      {text}
    </p>
  );
}

interface ReportInterview {
  interview_type: string;
  target_role: string | null;
  company_type: string | null;
  difficulty: string;
  started_at: string | null;
  ended_at: string | null;
  duration_seconds: number | null;
  status: string;
}

interface ReportRow {
  id: string;
  status: "pending" | "completed" | "failed";
  overall_score: number | null;
  strengths: unknown;
  weak_areas_summary: unknown;
  practice_actions: unknown;
  model_id: string | null;
  created_at: string;
  interviews: ReportInterview | null;
}

function ReportCard({ report }: { report: ReportRow }) {
  const interview = report.interviews;
  const strengths = Array.isArray(report.strengths) ? (report.strengths as string[]) : [];
  const practiceActions = Array.isArray(report.practice_actions) ? (report.practice_actions as string[]) : [];

  return (
    <div className="rounded-2xl border border-border bg-background p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <p className="font-body text-sm font-medium text-foreground">
          {interview?.interview_type ? capitalize(interview.interview_type) : "Interview"}
          {interview?.target_role ? ` · ${interview.target_role}` : ""}
        </p>
        <span className="font-body text-xs capitalize text-muted-foreground">{report.status}</span>
      </div>
      <p className="mt-1 font-body text-xs text-muted-foreground">
        {new Date(report.created_at).toLocaleDateString("en-IN", { year: "numeric", month: "short", day: "numeric" })}
        {interview?.duration_seconds ? ` · ${Math.round(interview.duration_seconds / 60)} min` : ""}
      </p>

      {report.status === "completed" && (
        <>
          {isStubReport(report.model_id) && (
            <span className="mt-2 inline-flex items-center rounded-full bg-amber-500/15 px-2 py-0.5 font-body text-[10px] font-semibold uppercase tracking-wide text-amber-700">
              Preview — stub interview engine, not a real evaluation
            </span>
          )}
          <p className="mt-3 font-metric text-2xl text-foreground">
            {report.overall_score !== null ? Number(report.overall_score).toFixed(0) : "—"}
          </p>
          {strengths.length > 0 && (
            <div className="mt-3">
              <p className="font-body text-xs font-medium text-muted-foreground">Strengths</p>
              <ul className="mt-1 list-inside list-disc font-body text-sm text-foreground">
                {strengths.map((item, i) => (
                  <li key={i}>{String(item)}</li>
                ))}
              </ul>
            </div>
          )}
          {practiceActions.length > 0 && (
            <div className="mt-3">
              <p className="font-body text-xs font-medium text-muted-foreground">Practice actions</p>
              <ul className="mt-1 list-inside list-disc font-body text-sm text-foreground">
                {practiceActions.map((item, i) => (
                  <li key={i}>{String(item)}</li>
                ))}
              </ul>
            </div>
          )}
        </>
      )}
      {report.status === "pending" && (
        <p className="mt-3 font-body text-sm text-muted-foreground">Report generation in progress.</p>
      )}
      {report.status === "failed" && (
        <p className="mt-3 font-body text-sm text-destructive">Report generation failed for this interview.</p>
      )}
    </div>
  );
}

function capitalize(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

interface ResumeRow {
  id: string;
  title: string;
  template: string;
  data: unknown;
  version: number;
  is_primary: boolean;
  updated_at: string;
}

/**
 * Resumes are stored as JSON Resume-shaped jsonb (BUILD_SPEC Part 4.3), but
 * the resume builder itself is Phase 3 (not yet built), so `data` can be
 * `{}` or any partial shape today. Renders the common JSON Resume
 * sections when present and says so plainly when there's nothing
 * recognizable yet, rather than guessing at a shape.
 */
function ResumeView({ resume }: { resume: ResumeRow }) {
  const data = (resume.data ?? {}) as Record<string, unknown>;
  const basics = isRecord(data.basics) ? data.basics : null;
  const work = Array.isArray(data.work) ? (data.work as Record<string, unknown>[]) : [];
  const education = Array.isArray(data.education) ? (data.education as Record<string, unknown>[]) : [];
  const skills = Array.isArray(data.skills) ? (data.skills as Record<string, unknown>[]) : [];
  const hasContent = basics || work.length > 0 || education.length > 0 || skills.length > 0;

  return (
    <div className="mt-4 space-y-4">
      <p className="font-body text-xs text-muted-foreground">
        {resume.title} · {resume.template} · v{resume.version}
        {resume.is_primary ? " · primary" : ""}
      </p>

      {!hasContent && <EmptyNote text="This student hasn't filled in resume content yet." />}

      {basics && (
        <div>
          {typeof basics.name === "string" && <p className="font-body text-sm font-medium text-foreground">{basics.name}</p>}
          {typeof basics.summary === "string" && (
            <p className="mt-1 font-body text-sm text-muted-foreground">{basics.summary}</p>
          )}
        </div>
      )}

      {work.length > 0 && (
        <div>
          <p className="font-body text-xs font-medium text-muted-foreground">Experience</p>
          <ul className="mt-1 space-y-2">
            {work.map((entry, i) => (
              <li key={i} className="font-body text-sm text-foreground">
                <span className="font-medium">{String(entry.position ?? "")}</span>
                {entry.name ? ` at ${String(entry.name)}` : ""}
              </li>
            ))}
          </ul>
        </div>
      )}

      {education.length > 0 && (
        <div>
          <p className="font-body text-xs font-medium text-muted-foreground">Education</p>
          <ul className="mt-1 space-y-2">
            {education.map((entry, i) => (
              <li key={i} className="font-body text-sm text-foreground">
                {String(entry.institution ?? "")}
                {entry.area ? ` — ${String(entry.area)}` : ""}
              </li>
            ))}
          </ul>
        </div>
      )}

      {skills.length > 0 && (
        <div>
          <p className="font-body text-xs font-medium text-muted-foreground">Skills</p>
          <p className="mt-1 font-body text-sm text-foreground">
            {skills.map((entry) => String(entry.name ?? "")).join(", ")}
          </p>
        </div>
      )}
    </div>
  );
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
